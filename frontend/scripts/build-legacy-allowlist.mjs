// Regenerates the legacy blog allowlist from the LIVE WordPress sitemap.
// The manifest referenced this script before it existed; it exists now, so the
// allowlist can be rebuilt from source rather than hand-maintained.
//
//   node scripts/build-legacy-allowlist.mjs
import { writeFileSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITEMAP = "https://oakpark-construction.com/post-sitemap.xml";
const ORIGIN_IP = "34.174.8.45";
const ORIGIN_HOST = "oakpark-construction.com";

const xml = await (await fetch(SITEMAP)).text();
const paths = [...xml.matchAll(/<loc>\s*(?:<!\[CDATA\[)?\s*(.*?)\s*(?:\]\]>)?\s*<\/loc>/gs)]
  .map((m) => m[1].trim())
  .filter((u) => u.startsWith(`https://${ORIGIN_HOST}/`))
  .map((u) => "/" + u.replace(`https://${ORIGIN_HOST}/`, "").replace(/\/+$/, ""))
  .filter((p) => p !== "/");   // "/blog" (the index) is kept — it is a real live page

const unique = [...new Set(paths)].sort();
if (unique.length < 200) {
  console.error(`REFUSING: sitemap yielded only ${unique.length} paths — expected ~233. Not overwriting.`);
  process.exit(1);
}

const vercel = JSON.parse(await (await import("fs/promises")).readFile(join(ROOT, "vercel.json"), "utf8"));
const redirected = new Set(vercel.redirects.map((r) => r.source.replace(/\/+$/, "")));
const collisions = unique.filter((p) => redirected.has(p));

writeFileSync(
  join(ROOT, "src/data/legacyBlogPaths.json"),
  JSON.stringify(
    { generated: new Date().toISOString().slice(0, 10), source: SITEMAP,
      origin_ip: ORIGIN_IP, origin_host: ORIGIN_HOST,
      count: unique.length, paths: unique, known_redirect_collisions: collisions },
    null, 1
  )
);
writeFileSync(
  join(ROOT, "api/_legacyManifest.js"),
  "// Generated by scripts/build-legacy-allowlist.mjs — do not edit by hand.\n" +
    "module.exports = " + JSON.stringify({ paths: unique, originIp: ORIGIN_IP, originHost: ORIGIN_HOST }, null, 1) + ";\n"
);
console.log(`allowlist rebuilt: ${unique.length} paths, ${collisions.length} redirect collision(s)`);
if (collisions.length) collisions.forEach((c) => console.log("  COLLISION:", c));
